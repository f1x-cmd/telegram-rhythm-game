/** 'pt-BR' → 'pt', 'zh-Hans-CN' → 'zh'; неизвестный код → null. */
function normalize(code) {
  if (!code) return null;
  const lower = String(code).toLowerCase();
  if (DICT[lower]) return lower;
  const short = lower.split(/[-_]/)[0];
  return DICT[short] ? short : null;
}

/** Автоопределение: сначала настройки Telegram, затем язык браузера. */
function detect() {
  const fromTelegram = normalize(getLanguage());
  if (fromTelegram) return fromTelegram;

  const list = typeof navigator !== 'undefined'
    ? [...(navigator.languages ?? []), navigator.language]
    : [];
  for (const code of list) {
    const match = normalize(code);
    if (match) return match;
  }
  return FALLBACK;
}

/** Валидный выбор ('auto' или известный код) либо null. */
function readPreference(value) {
  if (value === 'auto') return 'auto';
  return value ? normalize(value) : null;
}

// Локальная копия читается синхронно: иначе интерфейс успевает мигнуть
// автоопределённым языком, пока CloudStorage отвечает.
let preference = readPreference(peekLocal(KEY)) ?? 'auto';
let current = preference === 'auto' ? detect() : preference;
let formatter = new Intl.NumberFormat(LOCALES[current]);
const listeners = new Set();

function apply(code) {
  current = code;
  formatter = new Intl.NumberFormat(LOCALES[code] ?? code);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = code;
    document.documentElement.dir = RTL.has(code) ? 'rtl' : 'ltr';
  }
  for (const listener of listeners) listener(code);
}

/** Текущий язык интерфейса. */
export function language() {
  return current;
}

/** Что выбрано в настройках: 'auto' или конкретный код. */
export function languagePreference() {
  return preference;
}

/** Перевод с подстановкой `{name}`; неизвестный ключ отдаёт английский вариант. */
export function t(key, params) {
  const template = DICT[current]?.[key] ?? DICT[FALLBACK][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (
    params[name] !== undefined ? String(params[name]) : match
  ));
}

/** Текущий язык пишется справа налево. */
export function isRtl() {
  return RTL.has(current);
}

/** Числа в формате текущего языка (арабский — латинскими цифрами). */
export function formatNumber(value) {
  return formatter.format(value);
}

export function onLanguageChange(listener) {
  listeners.add(listener);
}

/** Подставляет переводы во все элементы с data-i18n. */
export function applyStaticText(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) {
    const text = t(element.dataset.i18n);
    const attr = element.dataset.i18nAttr;
    if (attr) element.setAttribute(attr, text);
    else element.textContent = text;
  }
}

/** Догружает выбор из облака Telegram: там он мог измениться на другом устройстве. */
export async function loadLanguage() {
  const saved = readPreference(await storage.get(KEY));
  if (saved) preference = saved;
  apply(preference === 'auto' ? detect() : preference);
  return current;
}

/** Ручной выбор: 'auto' возвращает автоопределение. */
export function setLanguage(code) {
  const next = readPreference(code);
  if (!next) return current;
  preference = next;
  storage.set(KEY, next);
  apply(next === 'auto' ? detect() : next);
  return current;
}

